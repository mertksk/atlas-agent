const DICTS: Record<Lang, Dict> = { en, zh, hi, es, fr, ar, bn, pt, ru, ur, de, tr };

interface I18nCtxType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: StrKey, vars?: Record<string, string | number>) => string;
}
const fallbackT = (k: StrKey, vars?: Record<string, string | number>) => interpolate(en[k], vars);
const I18nCtx = createContext<I18nCtxType>({ lang: "en", setLang: () => undefined, t: fallbackT });

function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");

  useEffect(() => {
    if (typeof window === "undefined") return;
    // Default is ALWAYS English — no browser-language auto-detection. Only an
    // explicit pick from the header selector (persisted) changes the language.
    const stored = window.localStorage.getItem("atlas_lang") as Lang | null;
    setLangState(stored && stored in DICTS ? stored : "en");
  }, []);

  useEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.has(lang) ? "rtl" : "ltr";
  }, [lang]);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") window.localStorage.setItem("atlas_lang", l);
  };
  const t = (k: StrKey, vars?: Record<string, string | number>) => interpolate(DICTS[lang][k] ?? en[k], vars);

  return <I18nCtx.Provider value={{ lang, setLang, t }}>{children}</I18nCtx.Provider>;
}

export const useI18n = () => useContext(I18nCtx);
